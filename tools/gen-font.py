#!/usr/bin/env python3
"""Generate kernel/core/font8x16.c from a Linux PSF1/PSF2 console font.

Phase 0 only needs 128 ASCII glyphs at 8x16. Fonts wider than 8 columns are
left-cropped to their leftmost 8 pixels; fonts shorter than 16 rows are
bottom-padded with blank rows.
"""
import glob
import gzip
import sys

PSF1_MAGIC = b'\x36\x04'
PSF2_MAGIC = 0x72B54A86


def load_psf(path):
    with open(path, 'rb') as fh:
        data = fh.read()
    if data[:2] == b'\x1f\x8b':
        data = gzip.decompress(data)
    if data[:2] == PSF1_MAGIC:
        mode = data[2]
        charsize = data[3]
        if mode & 1:
            raise ValueError('PSF1 unicode table unsupported')
        width, height = 8, charsize
        glyphs = data[4:4 + 256 * charsize]
        if len(glyphs) < 256 * charsize:
            raise ValueError('truncated PSF1')
        return width, height, glyphs, charsize
    if int.from_bytes(data[:4], 'little') != PSF2_MAGIC:
        raise ValueError('not a PSF font')
    fields = [int.from_bytes(data[4 + 4 * i:8 + 4 * i], 'little') for i in range(7)]
    _version, headersize, flags, length, charsize, height, width = fields
    off = headersize + (length * charsize if flags & 1 else 0)
    if off + length * charsize > len(data):
        raise ValueError('truncated PSF2')
    return width, height, data[off:off + length * charsize], charsize


def glyph_rows(width, height, glyphs, charsize, index):
    bytes_per_row = (width + 7) // 8
    base = index * charsize
    rows = []
    for row in range(16):
        if row < height:
            rows.append(glyphs[base + row * bytes_per_row])
        else:
            rows.append(0)
    return rows


def main(argv):
    if len(argv) == 2 and argv[1] == '--list':
        for path in sorted(glob.glob('/usr/share/consolefonts/*.psf*')):
            try:
                width, height, _g, _c = load_psf(path)
            except (ValueError, OSError):
                continue
            if height == 16 and width >= 8:
                print('%dx%d %s' % (width, height, path))
        return 0
    if len(argv) != 3:
        print('usage: gen-font.py FONT.psf[.gz] OUT.c', file=sys.stderr)
        return 2
    src, dst = argv[1], argv[2]
    width, height, glyphs, charsize = load_psf(src)
    if height > 16:
        print('font is taller than 16 rows', file=sys.stderr)
        return 1
    if len(glyphs) < 128 * charsize:
        print('font has fewer than 128 glyphs', file=sys.stderr)
        return 1

    out = []
    out.append('/* Generated by tools/gen-font.py from %s (%dx%d). Do not edit. */' %
               (src.split('/')[-1], width, height))
    out.append('#include <crug/types.h>')
    out.append('')
    out.append('const u8 crug_font8x16[128][16] = {')
    for index in range(128):
        rows = glyph_rows(width, height, glyphs, charsize, index)
        printable = ''.join(chr(index) if 32 <= index < 127 else '.')
        out.append('    { %s }, /* 0x%02x %s */' %
                   (', '.join('0x%02x' % b for b in rows), index, printable))
    out.append('};')
    out.append('')
    with open(dst, 'w', encoding='ascii') as fh:
        fh.write('\n'.join(out))
    print('wrote %s (%d glyphs from %s)' % (dst, 128, src))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
