#!/usr/bin/env python3
"""Generate kernel/lib/crc32c.c -- the reflected CRC32C (Castagnoli) table.

The kernel keeps a precomputed 256-entry table in .rodata so no runtime
initialisation is needed before the allocator or the filesystem come up.
Run from the repository root: python3 tools/gen-crc32c.py
"""

import os
import sys

POLY = 0x82F63B78
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'kernel', 'lib', 'crc32c.c')


def table():
    out = []
    for i in range(256):
        c = i
        for _ in range(8):
            c = (c >> 1) ^ POLY if (c & 1) else c >> 1
        out.append(c)
    return out


def main():
    t = table()
    lines = [
        '/*',
        ' * CRC32C (Castagnoli) -- reflected, no implicit initial or final xor.',
        ' *',
        ' * This is the raw primitive ext4 and JBD2 use for metadata checksums:',
        ' * the caller supplies the seed and chains calls to cover a byte range in',
        ' * pieces.  Table generated by tools/gen-crc32c.py; do not edit by hand.',
        ' */',
        '',
        '#include <crug/types.h>',
        '#include <crug/crc32c.h>',
        '',
        'static const u32 crc32c_table[256] = {',
    ]
    for i in range(0, 256, 4):
        lines.append('\t' + ', '.join('0x%08xu' % v for v in t[i:i + 4]) + ',')
    lines += [
        '};',
        '',
        'u32 crc32c(u32 seed, const void *data, usize len)',
        '{',
        '\tconst u8 *p = (const u8 *)data;',
        '\tu32 c = seed;',
        '\tusize i;',
        '',
        '\tfor (i = 0; i < len; i++)',
        '\t\tc = crc32c_table[(c ^ p[i]) & 0xFFu] ^ (c >> 8);',
        '\treturn c;',
        '}',
        '',
    ]
    with open(OUT, 'w') as fh:
        fh.write('\n'.join(lines))
    print('wrote %s (%d table entries)' % (os.path.relpath(OUT), len(t)))


if __name__ == '__main__':
    sys.exit(main())
